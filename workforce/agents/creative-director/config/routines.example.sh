#!/usr/bin/env bash
# ACME Bonsai Creative Director Team (Masahiko) — Claude Code Routines Setup
#
# All times are Eastern (America/New_York).

# ─────────────────────────────────────────────────────────────
# ROUTINE 1: Daily Brief Intake Triage
# Schedule: Daily — 9:00 AM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Masahiko reviews new creative briefs from CMO, Sales, Operations,
#   Customer Service, and direct Jane requests. For each: validate
#   purpose + audience + specs + deadline; estimate complexity + cost;
#   route to Hana / Iris / Mira; flag > $2K items for Jane. Posts
#   triaged list to #acme-creative-drafts; posts Jane-
#   approval items to #acme-creative-approvals.

# ─────────────────────────────────────────────────────────────
# ROUTINE 2: Daily Photography Production Status
# Schedule: Daily — 10:00 AM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Iris reports on yesterday's shoots + today's scheduled shoots.
#   Pulls new inventory from Tally needing photography coverage.
#   Flags any shoots within 48h missing release agreements. Posts
#   summary to #acme-creative-drafts.

# ─────────────────────────────────────────────────────────────
# ROUTINE 3: Daily Brand Asset Drift Check
# Schedule: Daily — 11:00 AM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Hana scans recent published content (website, social, email)
#   for brand drift — off-palette colors, unauthorized typography,
#   missing logo treatments, low contrast. Posts findings to
#   #acme-creative-alerts; opens revision tasks for
#   off-brand items.

# ─────────────────────────────────────────────────────────────
# ROUTINE 4: Weekly Asset Library Audit
# Schedule: Weekly — Monday 10:00 AM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Hana audits asset library: archive completed deliverables > 30d
#   old; identify duplicates; verify metadata completeness; report
#   library statistics (total assets, by kind, recent activity).
#   Posts to #acme-creative-library.

# ─────────────────────────────────────────────────────────────
# ROUTINE 5: Weekly Production Capacity Review
# Schedule: Weekly — Monday 11:00 AM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Masahiko reviews current production load across Hana / Iris /
#   Mira. Identifies conflicts, over-commitment, deadlines at risk.
#   Posts capacity report to #acme-creative-drafts.
#   Escalates conflicting priorities to Jane if cannot be resolved.

# ─────────────────────────────────────────────────────────────
# ROUTINE 6: Weekly Creative Output Report
# Schedule: Weekly — Friday 4:00 PM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Masahiko compiles weekly report: assets delivered, in-progress,
#   brand-drift signals resolved, top 3 next-week priorities. Posts
#   to #acme-creative-drafts. Cross-posts summary to CMO
#   and Director of Sales channels for visibility.

# ─────────────────────────────────────────────────────────────
# ROUTINE 7: Monthly Brand Consistency Audit
# Schedule: Monthly — Day 1 at 10:00 AM ET
# ─────────────────────────────────────────────────────────────
# Prompt:
#   Masahiko + Hana run comprehensive audit across all touchpoints
#   — website, social, email, packaging, signage, catalogs,
#   presentation materials. Identifies systemic drift. Reports
#   findings to #acme-creative-approvals for Jane
#   review. Opens brand-system-update if drift requires guideline
#   evolution.

